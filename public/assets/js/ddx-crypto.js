'use strict';
/**
 * DDX Transfer — the wire crypto, and the single source of truth for it.
 *
 * Three implementations of this exist: here (browser, WebCrypto),
 * electron/src/db/transfer.js (Node, node:crypto) and
 * flutter/lib/data/services/ddx_transfer_service.dart (Dart, package:cryptography).
 * They MUST agree byte for byte or a vault sent from one lands as garbage in
 * another, so every parameter below is stated explicitly rather than left to
 * a library default — a default that differs across three runtimes is exactly
 * the bug that would take a week to find.
 *
 *   key          32 random bytes, generated by the sender, never sent anywhere
 *   payload      gzip(snapshot JSON)  ->  split  ->  AES-256-GCM per chunk
 *   chunk wire   [12-byte IV][ciphertext || 16-byte GCM tag]
 *   manifest     AES-256-GCM over JSON, carried as { iv, ct } (base64)
 *   pinWrap      AES-256-GCM over the key itself, under
 *                PBKDF2-SHA256(code + ":" + pin, salt, 600000) -> 32 bytes
 *
 * The key lives in the URL fragment (`#k=`), which browsers never put on the
 * wire and servers therefore never see. `pinWrap` is the deliberate exception:
 * it is what makes a typed code work at all, and storing it is precisely the
 * moment this service becomes able to read the payload. It is optional for
 * that reason.
 */
(function (global) {
  const KEY_BYTES = 32;
  const IV_BYTES = 12;
  const TAG_BYTES = 16;
  const PBKDF2_ITERS = 600000;

  const enc = new TextEncoder();
  const dec = new TextDecoder();

  const randomBytes = (n) => crypto.getRandomValues(new Uint8Array(n));

  function toB64(bytes) {
    let s = '';
    for (const b of bytes) s += String.fromCharCode(b);
    return btoa(s);
  }
  function fromB64(s) {
    const bin = atob(String(s).replace(/-/g, '+').replace(/_/g, '/'));
    const out = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
    return out;
  }
  const toB64Url = (bytes) => toB64(bytes).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');

  const importKey = (raw, usages) =>
    crypto.subtle.importKey('raw', raw, { name: 'AES-GCM' }, false, usages);

  async function seal(keyBytes, plaintext) {
    const key = await importKey(keyBytes, ['encrypt']);
    const iv = randomBytes(IV_BYTES);
    const ct = new Uint8Array(await crypto.subtle.encrypt({ name: 'AES-GCM', iv }, key, plaintext));
    return { iv, ct };
  }

  async function open(keyBytes, iv, ct) {
    const key = await importKey(keyBytes, ['decrypt']);
    return new Uint8Array(await crypto.subtle.decrypt({ name: 'AES-GCM', iv }, key, ct));
  }

  /** Frames one chunk as [IV][ciphertext] so a chunk carries its own nonce. */
  async function sealChunk(keyBytes, plaintext) {
    const { iv, ct } = await seal(keyBytes, plaintext);
    const out = new Uint8Array(iv.length + ct.length);
    out.set(iv, 0);
    out.set(ct, iv.length);
    return out;
  }

  async function openChunk(keyBytes, framed) {
    const buf = new Uint8Array(framed);
    // `<`, not `<=`: an empty payload seals to exactly IV + tag and is a
    // perfectly valid authenticated chunk. Rejecting it would make an empty
    // (or nearly empty) vault the one thing that cannot be sent.
    if (buf.length < IV_BYTES + TAG_BYTES) throw new Error('chunk too short');
    return open(keyBytes, buf.subarray(0, IV_BYTES), buf.subarray(IV_BYTES));
  }

  async function sealJson(keyBytes, obj) {
    const { iv, ct } = await seal(keyBytes, enc.encode(JSON.stringify(obj)));
    return { iv: toB64(iv), ct: toB64(ct) };
  }

  async function openJson(keyBytes, sealed) {
    const plain = await open(keyBytes, fromB64(sealed.iv), fromB64(sealed.ct));
    return JSON.parse(dec.decode(plain));
  }

  /**
   * The sender seals under the code as the SERVER issued it (`ABCDEFGH`) and
   * the receiver types it as the screen shows it (`abcd-efgh`). Both sides
   * must derive from the same string or the typed-code path silently fails
   * every time, so both sides canonicalise first — including the Crockford
   * I/L -> 1 and O -> 0 substitutions, which are the whole reason the
   * alphabet excludes those letters.
   */
  const canonicalCode = (raw) => String(raw).toUpperCase().replace(/[^0-9A-Z]/g, '')
    .replace(/[IL]/g, '1').replace(/O/g, '0');
  const canonicalPin = (raw) => String(raw).replace(/[^0-9]/g, '');

  async function deriveWrapKey(code, pin, salt, iters) {
    const material = `${canonicalCode(code)}:${canonicalPin(pin)}`;
    const base = await crypto.subtle.importKey('raw', enc.encode(material), 'PBKDF2', false, ['deriveBits']);
    const bits = await crypto.subtle.deriveBits(
      { name: 'PBKDF2', salt, iterations: iters, hash: 'SHA-256' }, base, KEY_BYTES * 8,
    );
    return new Uint8Array(bits);
  }

  /** Seals the transfer key under the PIN, for the typed-code path only. */
  async function wrapKeyWithPin(keyBytes, code, pin) {
    const salt = randomBytes(16);
    const wrapKey = await deriveWrapKey(code, pin, salt, PBKDF2_ITERS);
    const { iv, ct } = await seal(wrapKey, keyBytes);
    return { iv: toB64(iv), ct: toB64(ct), salt: toB64(salt), iters: PBKDF2_ITERS };
  }

  async function unwrapKeyWithPin(pinWrap, code, pin) {
    const wrapKey = await deriveWrapKey(code, pin, fromB64(pinWrap.salt), pinWrap.iters);
    return open(wrapKey, fromB64(pinWrap.iv), fromB64(pinWrap.ct));
  }

  async function drainStream(stream) {
    const reader = stream.getReader();
    const parts = [];
    let total = 0;
    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      parts.push(value);
      total += value.length;
    }
    const out = new Uint8Array(total);
    let at = 0;
    for (const p of parts) { out.set(p, at); at += p.length; }
    return out;
  }

  /**
   * gzip is not universal (older Safari has no CompressionStream), so the
   * manifest records which of the two was actually used rather than the
   * sender assuming and the receiver guessing.
   */
  const canGzip = () => typeof CompressionStream === 'function' && typeof DecompressionStream === 'function';

  async function gzip(bytes) {
    if (!canGzip()) return { data: bytes, compression: 'none' };
    const s = new Blob([bytes]).stream().pipeThrough(new CompressionStream('gzip'));
    return { data: await drainStream(s), compression: 'gzip' };
  }

  async function gunzip(bytes, compression) {
    if (compression !== 'gzip') return bytes;
    if (!canGzip()) throw new Error('gzip_unsupported');
    const s = new Blob([bytes]).stream().pipeThrough(new DecompressionStream('gzip'));
    return drainStream(s);
  }

  function splitChunks(bytes, maxPlainBytes) {
    const out = [];
    for (let at = 0; at < bytes.length; at += maxPlainBytes) {
      out.push(bytes.subarray(at, Math.min(at + maxPlainBytes, bytes.length)));
    }
    // An empty payload would produce no chunks at all, and commit rejects
    // chunkCount < 1 — send one empty-but-authenticated chunk instead.
    return out.length ? out : [new Uint8Array(0)];
  }

  function concatChunks(list) {
    const total = list.reduce((n, c) => n + c.length, 0);
    const out = new Uint8Array(total);
    let at = 0;
    for (const c of list) { out.set(c, at); at += c.length; }
    return out;
  }

  global.DDXCrypto = {
    KEY_BYTES, IV_BYTES, TAG_BYTES, PBKDF2_ITERS,
    randomBytes, toB64, fromB64, toB64Url,
    sealChunk, openChunk, sealJson, openJson,
    wrapKeyWithPin, unwrapKeyWithPin, canonicalCode, canonicalPin,
    gzip, gunzip, canGzip, splitChunks, concatChunks,
    newKey: () => randomBytes(KEY_BYTES),
  };
})(window);
